def solution(numbers):
    # ───────────────────────────────────────────────────────────
    # 말판 단위 유틸: 전처리판 = 포화 이진트리 좌석표 길이 맞추기
    # ───────────────────────────────────────────────────────────
    def 포화길이로_왼쪽0채우기(이진문자열: str) -> str:
        """
        [전처리판]
        - 말판(숫자 하나)에 대해, 이번 배치(컷)를 실제 심판하기 전에
          포화 이진트리 좌석표(1,3,7,15,…) 길이로 '왼쪽'을 0으로 채운다.
        - 말 비유: 좌석표가 더 커야 하니까, 맨 앞쪽에 빈자리(0)를 끼워넣어
          '완전 좌석표' 크기로 키운다.
        """
        포화길이 = 1
        # 1,3,7,15,...(2^h - 1) 중 현재 길이 이상이 될 때까지 키움
        while 포화길이 < len(이진문자열):
            포화길이 = 포화길이 * 2 + 1
        # zfill: 문자열의 '왼쪽'에 '0'을 채워 길이를 맞춘다 (더미 좌석 추가)
        return 이진문자열.zfill(포화길이)

    # ───────────────────────────────────────────────────────────
    # 말판 단위 유틸: 심판판 = 프레임(서브트리) 단위 재귀 판정
    # ───────────────────────────────────────────────────────────
    """
        [심판판]
        - 입력: 전처리판에서 길이를 맞춘 '중위 순서 좌석열'(왼→루트→오른쪽의 상대적 순서)
        - 규칙(로컬 판정):
          내부 노드(루트 좌석)가 0(더미)이면, 해당 서브트리(왼/오)에는 1(실노드)이 절대로 있으면 안 된다.
        - 전체(글로벌 컷 판정): 모든 프레임이 통과되면 이 컷(배치)은 성공.
        """
    def 프레임_재귀검사(구간: str) -> bool:
            # [프레임] 리프(좌석 1개)는 언제나 OK
            if len(구간) == 1:
                return True

            가운데 = len(구간) // 2      # 이 구간 프레임의 루트(부모 좌석)
            루트 = 구간[가운데]
            왼쪽, 오른쪽 = 구간[:가운데], 구간[가운데 + 1:]

            # [로컬 판정] 부모가 더미(0)면 아래(왼/오)에 실노드(1)가 있어선 안 됨
            if 루트 == '0' and ('1' in 왼쪽 or '1' in 오른쪽):
                return False

            # [프레임 전이] 양쪽 서브 프레임도 같은 규칙으로 재귀 심판
            return 프레임_재귀검사(왼쪽) and 프레임_재귀검사(오른쪽)

         

    # ───────────────────────────────────────────────────────────
    # 가능세계 판정(말판 단위): 최소 포화 패딩 한 번만 검사 (정석)
    # ───────────────────────────────────────────────────────────
    결과 = []
    for 수 in numbers:
        원본이진 = format(수, 'b')

        # [전처리판] 최소 포화 좌석표로 맞춤 (왼쪽 0 채우기)
        패딩 = 포화길이로_왼쪽0채우기(원본이진)

        # [심판판] 프레임(서브트리) 단위 재귀 판정 → 한 번만 검사
        가능 = 프레임_재귀검사(패딩)

        # [가능세계 판정] 말판(숫자) 단위 최종 판단
        결과.append(1 if 가능 else 0)

    return 결과


